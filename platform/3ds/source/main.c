/* Picking a language, as a list.
 *
 * This stepped through the languages one press at a time until a console proved
 * why that is wrong: the font check refuses a language the console cannot draw,
 * and a refused entry in a cycle is a wall. Japanese was reachable, Chinese was
 * refused, and everything after Chinese was unreachable - including the way back.
 *
 * A list has no order to be trapped in. Every language is on screen at once, each
 * written in its own script, and the ones this console has no font for are shown
 * greyed rather than hidden: "my language is not here" is a worse answer than "my
 * language is here and this console cannot draw it".
 *
 * Those rows cannot be written in their own script either - that is what being
 * undrawable means - so they fall back to their language code, which is ASCII and
 * always renders.
 */
#define LANG_ROWS 9

static const daemoon_lang_t k_lang_order[LANG_ROWS - 1] = {
    DAEMOON_LANG_EN, DAEMOON_LANG_KO, DAEMOON_LANG_JA, DAEMOON_LANG_ZH_HANS,
    DAEMOON_LANG_ZH_HANT, DAEMOON_LANG_ES, DAEMOON_LANG_FR, DAEMOON_LANG_DE
};

/* Row 0 follows the console; rows 1.. are k_lang_order. */
static void language_row_text(size_t row, char *out, size_t cap, int *drawable)
{
    if (row == 0) {
        const char *args[1];

        args[0] = daemoon_lang_name(console_language());
        (void)daemoon_strf(out, cap, DAEMOON_STR_SETTINGS_LANGUAGE_AUTO, args, 1);
        *drawable = 1;
        return;
    }
    {
        daemoon_lang_t lang = k_lang_order[row - 1];

        *drawable = daemoon_gfx_language_drawable(lang);
        (void)daemoon_strlcpy(out, cap,
                              *drawable ? daemoon_lang_name(lang)
                                        : daemoon_lang_code(lang));
    }
}

static size_t language_current_row(void)
{
    daemoon_lang_t chosen;
    size_t i;

    if (g_config.language[0] == '\0' ||
        daemoon_i18n_language_from_code(g_config.language, &chosen) != DAEMOON_OK) {
        return 0;
    }
    for (i = 0; i < LANG_ROWS - 1; ++i) {
        if (k_lang_order[i] == chosen) {
            return i + 1;
        }
    }
    return 0;
}

/* Returns 1 when the setting changed. */
static int choose_language(void)
{
    size_t selected = language_current_row();
    int changed = 0;

    daemoon_3ds_trace("settings/language-open", NULL);

    while (aptMainLoop()) {
        u32 down;
        size_t i;
        float y;

        hidScanInput();
        down = hidKeysDown();

        daemoon_gfx_frame_begin();

        daemoon_gfx_top();
        daemoon_gfx_rect(0.0f, 0.0f, GFX_TOP_W, 28.0f, GFX_ACCENT_D);
        daemoon_gfx_text(12.0f, 6.0f, 0.55f, GFX_TEXT,
                         daemoon_str(DAEMOON_STR_SETTINGS_LANGUAGE));
        {
            char text[96];
            int drawable = 1;

            language_row_text(selected, text, sizeof(text), &drawable);
            daemoon_gfx_text_fit(14.0f, 60.0f, GFX_TOP_W - 28.0f, 0.7f,
                                 drawable ? GFX_TEXT : GFX_TEXT_DIM, text);
            if (!drawable) {
                char body[320];
                const char *args[1];

                args[0] = daemoon_lang_code(k_lang_order[selected - 1]);
                (void)daemoon_strf(body, sizeof(body), DAEMOON_STR_SETTINGS_NO_FONT,
                                   args, 1);
                (void)daemoon_gfx_text_wrapped(14.0f, 110.0f, GFX_TOP_W - 28.0f, 0.38f,
                                               GFX_WARN, body);
            }
        }

        daemoon_gfx_bottom();
        y = 6.0f;
        for (i = 0; i < LANG_ROWS; ++i) {
            char text[96];
            int drawable = 1;

            language_row_text(i, text, sizeof(text), &drawable);
            daemoon_gfx_rect(6.0f, y, GFX_BOTTOM_W - 12.0f, 22.0f,
                             i == selected ? GFX_ACCENT : GFX_PANEL);
            daemoon_gfx_text_fit(12.0f, y + 3.0f, GFX_BOTTOM_W - 24.0f, 0.4f,
                                 drawable ? GFX_TEXT : GFX_TEXT_DIM, text);
            y += 24.0f;
        }
        daemoon_gfx_text(8.0f, GFX_SCREEN_H - 16.0f, 0.32f, GFX_TEXT_DIM,
                         daemoon_str(DAEMOON_STR_HINT_CHOOSE));

        daemoon_gfx_frame_end();

        if (down & KEY_B) {
            break;
        }
        if (down & KEY_A) {
            if (selected == 0) {
                daemoon_lang_t sys = console_language();

                g_config.language[0] = '\0';
                (void)daemoon_gfx_set_language(sys);
                daemoon_i18n_set_language(sys);
                changed = 1;
                break;
            }
            {
                daemoon_lang_t lang = k_lang_order[selected - 1];

                /* Refused rather than accepted: every screen after this one would
                 * be blank, including this one. The reason is already on the top
                 * screen, so the press simply does nothing. */
                if (!daemoon_gfx_language_drawable(lang)) {
                    continue;
                }
                /* The font moves with the language. Changing one without the
                 * other is how a Korean console ended up drawing Hangul as
                 * replacement characters. */
                if (!daemoon_gfx_set_language(lang)) {
                    continue;
                }
                (void)daemoon_strlcpy(g_config.language, sizeof(g_config.language),
                                      daemoon_lang_code(lang));
                daemoon_i18n_set_language(lang);
                changed = 1;
                break;
            }
        }
        if ((down & KEY_UP) && selected > 0) {
            --selected;
        }
        if ((down & KEY_DOWN) && selected + 1 < LANG_ROWS) {
            ++selected;
        }
    }

    return changed;
}

/* What both pairing paths end at.
 *
 * A typed code and a scanned one differ only in where the six digits and the
 * server address came from; from here they are the same exchange. The token is
 * written to the same file the FTP push writes, so a console paired from the
 * screen and one paired from a desktop are in identical states afterwards.
 */
static int finish_pairing(const char *grant, const char *code)
{
    char token[DAEMOON_TOKEN_MAX];
    char device_id[DAEMOON_DEVICE_ID_MAX];
    daemoon_result_t r;

    if (g_config.server_url[0] == '\0') {
        message(daemoon_str(DAEMOON_STR_APP_TITLE),
                daemoon_str(DAEMOON_STR_PAIR_NO_SERVER), GFX_WARN);
        return 0;
    }

    /* The network may not have been opened at startup: a console with no server
     * configured has no reason to hold a soc:U session, and this is the moment it
     * gets one. */
    if (daemoon_3ds_net_init() != DAEMOON_OK) {
        report(DAEMOON_STR_OP_SYNC, DAEMOON_ERR_NETWORK_ERROR);
        return 0;
    }

    /* Whether this console is claiming to be one the server already knows. It goes
     * out as an ordinary bearer header, and the server rotates that device instead
     * of minting another - so if a console keeps appearing twice, this line is the
     * first thing to look at. */
    daemoon_3ds_trace("pair/bearer",
                      (g_env.token != NULL && g_env.token[0] != '\0') ? "yes" : "no");
    daemoon_3ds_trace("pair/exchange", grant);
    draw_loading(DAEMOON_STR_PAIR_TITLE, 0, 0);

    r = daemoon_api_pair(&g_env, grant, code, g_config.device_label,
                         DAEMOON_PLATFORM_3DS, token, sizeof(token),
                         device_id, sizeof(device_id));
    daemoon_3ds_trace("pair/result", daemoon_result_code(r));
    if (r != DAEMOON_OK) {
        report(DAEMOON_STR_PAIR_TITLE, r);
        return 0;
    }
    /* The same id back means the server rotated this console's device. A different
     * one means it made another, and the panel will show two. */
    daemoon_3ds_trace("pair/device",
                      (g_config.device_id[0] != '\0' &&
                       strcmp(g_config.device_id, device_id) == 0)
                          ? "same"
                          : "new");

    /* The token this console was already holding went out with the request, as an
     * ordinary bearer header, and that is deliberate: it is how the server knows
     * this is the same console pairing again rather than a new one. It rotates the
     * existing device in place, so one console stays one row and the old credential
     * stops working the moment the new one is issued.
     *
     * A console with no token, or one the server does not know, becomes a new
     * device - which is right for a fresh SD card. */
    (void)daemoon_strlcpy(g_config.token, sizeof(g_config.token), token);
    (void)daemoon_strlcpy(g_config.device_id, sizeof(g_config.device_id), device_id);
    g_env.token = g_config.token;

    /* The archive first, because that is where the credential belongs. The file
     * only carries the address and the label now. */
    r = daemoon_3ds_secret_save(&g_env, g_config.token, g_config.device_id);
    daemoon_3ds_trace("secret/saved", daemoon_result_code(r));
    if (r != DAEMOON_OK) {
        /* The token is live but only in memory. Saying so beats a console that
         * syncs today and is a stranger tomorrow. */
        report(DAEMOON_STR_PAIR_TITLE, r);
        return 1;
    }
    (void)daemoon_3ds_config_save(DAEMOON_3DS_CONFIG_PATH, &g_config);

    message(daemoon_str(DAEMOON_STR_APP_TITLE),
            daemoon_str(DAEMOON_STR_PAIR_DONE), GFX_OK);
    return 1;
}

static int pair_with_typed_code(void)
{
    char code[DAEMOON_PAIR_CODE_MAX];

    code[0] = '\0';
    if (!edit_field(DAEMOON_STR_PAIR_TITLE, "000000", code, sizeof(code))) {
        return 0;
    }
    if (code[0] == '\0') {
        return 0;
    }
    return finish_pairing("device_code", code);
}

/* Drawn once per camera frame while the scan runs. Returning 0 stops it, which is
 * the only way out of a screen that is otherwise waiting on hardware. */
static int scan_frame(void *user)
{
    const C2D_Image *preview;
    const daemoon_3ds_qr_stats_t *st;
    char line[128];
    u32 down;

    (void)user;
    if (!aptMainLoop()) {
        return 0;
    }
    hidScanInput();
    down = hidKeysDown();

    preview = daemoon_3ds_qr_preview();
    st = daemoon_3ds_qr_last_stats();

    daemoon_gfx_frame_begin();
    daemoon_gfx_top();
    if (preview != NULL && st->frames > 0) {
        /* What the camera sees, filling the screen. Without this a scan cannot be
         * aimed, and a scan that cannot be aimed does not work - which is exactly
         * how the first version of this failed. */
        C2D_DrawImageAt(*preview, 0.0f, 0.0f, 0.0f, NULL,
                        GFX_TOP_W / (float)DAEMOON_3DS_CAM_W,
                        GFX_SCREEN_H / (float)DAEMOON_3DS_CAM_H);
    } else {
        daemoon_gfx_rect(0.0f, 0.0f, GFX_TOP_W, GFX_SCREEN_H, GFX_PANEL);
    }
    daemoon_gfx_rect(0.0f, 0.0f, GFX_TOP_W, 22.0f, GFX_ACCENT_D);
    daemoon_gfx_text(10.0f, 4.0f, 0.45f, GFX_TEXT, daemoon_str(DAEMOON_STR_PAIR_SCAN));

    daemoon_gfx_bottom();
    (void)daemoon_gfx_text_wrapped(10.0f, 14.0f, GFX_BOTTOM_W - 20.0f, 0.42f, GFX_TEXT,
                                   daemoon_str(DAEMOON_STR_PAIR_AIM));
    /* The three numbers that tell the failures apart, on screen rather than only in
     * a file: no frames is a camera that never started, a mean near zero is a lens
     * covered, and codes seen without a decode is a code too far or out of focus. */
    (void)snprintf(line, sizeof(line),
                   "frames %u   light %u   codes %d   %s   %s",
                   st->frames, st->mean_luma, st->codes_seen,
                   st->camera ? "inner" : "outer",
                   daemoon_3ds_cam_layout_name(st->layout));
    daemoon_gfx_text(10.0f, GFX_SCREEN_H - 58.0f, 0.38f, GFX_TEXT_DIM, line);
    /* Where the time goes. Four candidates and no way to tell them apart by
     * reading, so the console reports which one is expensive. */
    (void)snprintf(line, sizeof(line),
                   "ms  cap %u  tile %u  draw %u  dec %u   buferr %u",
                   st->ms_capture, st->ms_tile, st->ms_draw, st->ms_decode,
                   st->buffer_errors);
    daemoon_gfx_text(10.0f, GFX_SCREEN_H - 40.0f, 0.38f, GFX_TEXT_DIM, line);
    daemoon_gfx_text(10.0f, GFX_SCREEN_H - 20.0f, 0.36f, GFX_TEXT_DIM,
                     daemoon_str(DAEMOON_STR_PAIR_SWITCH));
    daemoon_gfx_frame_end();

    if (down & KEY_B) {
        return 0;
    }
    if (down & (KEY_L | KEY_R)) {
        return 2;
    }
    if (down & (KEY_X | KEY_Y)) {
        return 3;
    }
    return 1;
}

static int pair_by_scanning(void)
{
    char payload[512];
    daemoon_pair_payload_t parsed;
    daemoon_result_t r;
    daemoon_3ds_trace("pair/scan", NULL);
    r = daemoon_3ds_qr_scan(scan_frame, NULL, payload, sizeof(payload));
    daemoon_3ds_trace("pair/scan-done", daemoon_result_code(r));

    if (r == DAEMOON_ERR_USER_CANCELLED) {
        return 0;
    }
    if (r == DAEMOON_ERR_BACKEND_ERROR) {
        message(daemoon_str(DAEMOON_STR_APP_TITLE),
                daemoon_str(DAEMOON_STR_PAIR_NO_CAMERA), GFX_DANGER);
        return 0;
    }
    if (r != DAEMOON_OK) {
        report(DAEMOON_STR_PAIR_TITLE, r);
        return 0;
    }

    if (daemoon_pair_parse(payload, strlen(payload), &parsed) != DAEMOON_OK) {
        /* Something was read and it was not ours. Said plainly, because "scan
         * failed" would send somebody back to hold the console steadier at a code
         * that was never going to work. */
        message(daemoon_str(DAEMOON_STR_APP_TITLE),
                daemoon_str(DAEMOON_STR_PAIR_WRONG_CODE), GFX_WARN);
        return 0;
    }

    /* The address travels with the code, which is the whole reason for scanning
     * rather than typing. */
    (void)daemoon_strlcpy(g_config.server_url, sizeof(g_config.server_url),
                          parsed.server);
    g_env.server_url = g_config.server_url;
    return finish_pairing("qr", parsed.code);
}

static void action_settings(void)
{
    const daemoon_str_id_t *labels = k_settings_labels;
    int selected = 0;
    int dirty = 0;

    daemoon_3ds_trace("settings/open", NULL);

    while (aptMainLoop()) {
        u32 down;
        int edited = 0;

        hidScanInput();
        down = hidKeysDown();

        daemoon_gfx_frame_begin();
        draw_settings(selected);
        daemoon_gfx_frame_end();

        if (down & KEY_B) {
            break;
        }
        if (down & KEY_A) {
            switch (selected) {
            case 0:
                edited = edit_field(labels[0], "http://192.168.1.10:8080",
                                    g_config.server_url, sizeof(g_config.server_url));
                if (edited) {
                    /* The same trailing slash rule the parser applies, so typing
                     * one here and pushing one over FTP end up identical. */
                    size_t len = strlen(g_config.server_url);

                    while (len > 0 && g_config.server_url[len - 1] == '/') {
                        g_config.server_url[--len] = '\0';
                    }
                }
                break;
            case 1:
                edited = edit_field(labels[1], "daemoonctl pair", g_config.token,
                                    sizeof(g_config.token));
                if (edited) {
                    /* Typed by hand, and still a credential: it goes where the
                     * paired one goes, not onto the card. */
                    daemoon_result_t sr = daemoon_3ds_secret_save(&g_env,
                                                                  g_config.token,
                                                                  g_config.device_id);

                    daemoon_3ds_trace("secret/typed", daemoon_result_code(sr));
                    g_env.token = g_config.token[0] != '\0' ? g_config.token : NULL;
                }
                break;
            case 2:
                edited = edit_field(labels[2], "3DS", g_config.device_label,
                                    sizeof(g_config.device_label));
                break;
            case 3:
                /* No keyboard for this one - it steps through the list, so the
                 * screen changes language under the cursor and the choice is
                 * judged by reading it. */
                edited = choose_language();
                break;
            case 4:
                edited = pair_by_scanning();
                break;
            default:
                edited = pair_with_typed_code();
                break;
            }
            dirty = dirty || edited;
        }
        if ((down & KEY_UP) && selected > 0) {
            --selected;
        }
        if ((down & KEY_DOWN) && selected < SETTINGS_ROWS - 1) {
            ++selected;
        }
    }

    if (!dirty) {
        return;
    }

    {
        daemoon_result_t r = daemoon_3ds_config_save(DAEMOON_3DS_CONFIG_PATH, &g_config);

        daemoon_3ds_trace("settings/save", daemoon_result_code(r));
        if (r != DAEMOON_OK) {
            message(daemoon_str(DAEMOON_STR_APP_TITLE),
                    daemoon_str(DAEMOON_STR_SETTINGS_SAVE_FAILED), GFX_DANGER);
            return;
        }

        /* The environment points at these buffers, so the new values are already
         * in use. What is not is the network, which is opened once at startup and
         * may not have been opened at all. */
        g_env.token = g_config.token[0] != '\0' ? g_config.token : NULL;
        g_net_ctx.ca_bundle = g_config.ca_bundle;

    /* The token lives in this application's own save archive, not on the card.
     *
     * A console paired before that change has one in config.txt, so it is moved
     * across on the first run that finds it there and struck from the file. The
     * card stops being a credential from that moment, which is the whole point:
     * revocation answers a lost card, and revocation is a thing you have to notice
     * you need. */
    {
        char token[DAEMOON_TOKEN_MAX];
        char device_id[DAEMOON_DEVICE_ID_MAX];

        if (daemoon_3ds_secret_load(&g_env, token, sizeof(token), device_id,
                                    sizeof(device_id)) == DAEMOON_OK) {
            (void)daemoon_strlcpy(g_config.token, sizeof(g_config.token), token);
            (void)daemoon_strlcpy(g_config.device_id, sizeof(g_config.device_id),
                                  device_id);
            daemoon_3ds_trace("secret/loaded", device_id);
        } else if (g_config.token[0] != '\0') {
            daemoon_result_t mr = daemoon_3ds_secret_save(&g_env, g_config.token,
                                                          g_config.device_id);

            daemoon_3ds_trace("secret/migrated", daemoon_result_code(mr));
            if (mr == DAEMOON_OK) {
                /* Rewritten without it: config_save no longer emits a token, so
                 * this is what actually takes it off the card. */
                (void)daemoon_3ds_config_save(DAEMOON_3DS_CONFIG_PATH, &g_config);
            }
        }
    }
        if (daemoon_3ds_config_can_sync(&g_config)) {
            (void)daemoon_3ds_net_init();
        }
        message(daemoon_str(DAEMOON_STR_APP_TITLE),
                daemoon_str(DAEMOON_STR_SETTINGS_SAVED), GFX_OK);
    }
}

static void action_survey(void)
{
    daemoon_stream_t *out = NULL;
    daemoon_result_t r;
    size_t i;

    r = g_env.fs->open(g_env.fs_ctx, DAEMOON_3DS_WORK_DIR "/survey.txt",
                       DAEMOON_OPEN_WRITE, &out);
    if (r != DAEMOON_OK) {
        report(DAEMOON_STR_OP_SURVEY, r);
        return;
    }

    {
        char header[160];
        daemoon_strbuf_t hb;

        daemoon_strbuf_init(&hb, header, sizeof(header));
        daemoon_strbuf_add(&hb, "# DaeMoon build ");
        daemoon_strbuf_add(&hb, DAEMOON_BUILD_STAMP);
        daemoon_strbuf_add(&hb, " font=");
        daemoon_strbuf_add_uint(&hb, (unsigned long long)daemoon_gfx_font_source());
        /* Which languages this console could draw at all, as one bit each. The
         * font question this project spent weeks on is a fact about the console,
         * so it belongs in the file that describes one. */
        daemoon_strbuf_add(&hb, " drawable=");
        {
            static const daemoon_lang_t k_all[] = {
                DAEMOON_LANG_EN, DAEMOON_LANG_KO, DAEMOON_LANG_JA,
                DAEMOON_LANG_ZH_HANS, DAEMOON_LANG_ZH_HANT, DAEMOON_LANG_ES,
                DAEMOON_LANG_FR, DAEMOON_LANG_DE
            };
            size_t li;

            for (li = 0; li < sizeof(k_all) / sizeof(k_all[0]); ++li) {
                if (!daemoon_gfx_language_drawable(k_all[li])) {
                    continue;
                }
                daemoon_strbuf_add(&hb, daemoon_lang_code(k_all[li]));
                daemoon_strbuf_addc(&hb, ',');
            }
        }
        daemoon_strbuf_add(&hb, " ascii_names=");
        daemoon_strbuf_add_uint(&hb, (unsigned long long)g_save_ctx.ascii_names);
        daemoon_strbuf_add(&hb, " smdh_lang=");
        daemoon_strbuf_add_uint(&hb, (unsigned long long)g_save_ctx.smdh_language);
        daemoon_strbuf_addc(&hb, '\n');
        (void)daemoon_stream_write(out, header, hb.len);
    }

    for (i = 0; i < CUR->count; ++i) {
        daemoon_title_t *t = &CUR->titles[i];
        daemoon_3ds_secure_value_t secure;
        daemoon_save_t *save = NULL;
        unsigned long long bytes = 0;
        char line[512];
        daemoon_strbuf_t sb;
        daemoon_result_t sr;
        daemoon_result_t or_;

        memset(&secure, 0, sizeof(secure));
        sr = daemoon_3ds_read_secure_value(t, &secure);

        or_ = g_env.save->open_save(g_env.save_ctx, t, &save);
        if (or_ == DAEMOON_OK) {
            (void)g_env.save->list_entries(g_env.save_ctx, save, survey_count_cb, &bytes);
            (void)g_env.save->close_save(g_env.save_ctx, save);
        }

        daemoon_strbuf_init(&sb, line, sizeof(line));
        daemoon_strbuf_add(&sb, t->id);
        daemoon_strbuf_add(&sb, "\tsave=");
        daemoon_strbuf_add(&sb, or_ == DAEMOON_OK ? "yes" : daemoon_result_code(or_));
        daemoon_strbuf_add(&sb, "\tbytes=");
        daemoon_strbuf_add_uint(&sb, bytes);
        daemoon_strbuf_add(&sb, "\tsecure=");
        if (sr != DAEMOON_OK) {
            daemoon_strbuf_add(&sb, daemoon_result_code(sr));
        } else if (secure.exists) {
            static const char digits[] = "0123456789ABCDEF";
            char hex[17];
            int k;

            for (k = 0; k < 16; ++k) {
                hex[k] = digits[(secure.value >> ((15 - k) * 4)) & 0xf];
            }
            hex[16] = '\0';
            daemoon_strbuf_add(&sb, hex);
        } else {
            daemoon_strbuf_add(&sb, "none");
        }

        daemoon_strbuf_add(&sb, "\ticon=");
        daemoon_strbuf_add(&sb, (i < MAX_ICONS && CUR->icons[i].loaded) ? "yes" : "no");

        /* Why the name is what it is, and the raw Result when it is not a name.
         * A wire code says "not supported"; a Result says which module said it,
         * and this question has already cost two trips to a console. */
        {
            char real[DAEMOON_NAME_MAX];
            daemoon_result_t nr = daemoon_3ds_title_name(g_save_ctx.media, tid_of(t),
                                                         g_save_ctx.smdh_language, 0,
                                                         real, sizeof(real));

            daemoon_strbuf_add(&sb, "\tname=");
            daemoon_strbuf_add(&sb, nr == DAEMOON_OK ? "smdh" : daemoon_result_code(nr));
            {
                const daemoon_3ds_name_probe_t *pr = daemoon_3ds_last_name_probe();

                daemoon_strbuf_add(&sb, " lang=");
                daemoon_strbuf_add_int(&sb, pr->name_lang);
                if (pr->rejected_non_ascii) {
                    /* A name was there and could not be drawn. That is the font,
                     * not the lookup. */
                    daemoon_strbuf_add(&sb, " undrawable");
                }
            }
            if (nr != DAEMOON_OK) {
                /* Every route and what it said. One coarse word covered three
                 * different causes and cost four trips to a console; this is the
                 * shape of a diagnostic that ends the guessing. */
                const daemoon_3ds_name_probe_t *pr = daemoon_3ds_last_name_probe();

                daemoon_strbuf_add(&sb, " direct=");
                append_hex32(&sb, (unsigned long)pr->open_direct);
                daemoon_strbuf_add(&sb, " direct2=");
                append_hex32(&sb, (unsigned long)pr->open_direct2);
                daemoon_strbuf_add(&sb, " archive=");
                append_hex32(&sb, (unsigned long)pr->open_archive);
                daemoon_strbuf_add(&sb, " file=");
                append_hex32(&sb, (unsigned long)pr->open_file);
                daemoon_strbuf_add(&sb, " read=");
                append_hex32(&sb, (unsigned long)pr->read);
                daemoon_strbuf_add(&sb, " got=");
                daemoon_strbuf_add_uint(&sb, pr->read_bytes);
            }
            daemoon_strbuf_add(&sb, "\treal=");
            daemoon_strbuf_add(&sb, nr == DAEMOON_OK ? real : "-");
        }

        /* The name as the console knows it, in whatever script that is. This file
         * is read on a machine with fonts. */
        daemoon_strbuf_add(&sb, "\t");
        daemoon_strbuf_add(&sb, t->name);
        daemoon_strbuf_addc(&sb, '\n');

        (void)daemoon_stream_write(out, line, sb.len);
    }

    r = daemoon_stream_close(out);

    /* Everything above went to the hardware rather than to the cache, so the cache
     * is now the older of the two answers. Throwing it away also makes this the
     * button to press when a name or an icon looks wrong: the next list is read
     * from the console again. */
    daemoon_3ds_cache_forget(g_save_ctx.cache);

    report(DAEMOON_STR_OP_SURVEY, r);
}

/* The conformance suite writes, clears and commits a real save archive. It exists
 * to prove this backend behaves the way core is entitled to assume, and running
 * it on a title someone plays would be indefensible. */
static void action_self_test(void)
{
    daemoon_backend_under_test_t ut;
    daemoon_str_ref_t ask;
    char path[DAEMOON_PATH_MAX * 2];
    char body[256];
    int before;

    if (CUR->count == 0) {
        return;
    }

    {
        const char *args[1];

        args[0] = CUR->titles[CUR->selected].name;
        (void)daemoon_strf(body, sizeof(body), DAEMOON_STR_SELFTEST_WARNING, args, 1);
    }
    message(daemoon_str(DAEMOON_STR_APP_TITLE), body, GFX_DANGER);

    memset(&ask, 0, sizeof(ask));
    ask.id = DAEMOON_STR_CONFIRM_RESTORE;
    ask.args[0] = CUR->titles[CUR->selected].name;
    ask.nargs = 1;
    if (!g_env.ui->confirm(g_env.ui_ctx, &ask)) {
        return;
    }

    report(DAEMOON_STR_OP_BACKUP, daemoon_sync_backup_local(&g_env, &g_archive, &CUR->titles[CUR->selected],
                                               path, sizeof(path)));

    memset(&ut, 0, sizeof(ut));
    ut.name = "3ds";
    ut.backend = &daemoon_3ds_save_backend;
    ut.ctx = &g_save_ctx;
    ut.title = &CUR->titles[CUR->selected];
    ut.other = NULL;
    ut.scratch = g_scratch;
    ut.scratch_len = sizeof(g_scratch);

    before = daemoon_test_failures;
    daemoon_backend_conformance(&ut);

    (void)snprintf(body, sizeof(body), "%d checks, %d failures. %s",
                   daemoon_test_checks, daemoon_test_failures - before,
                   daemoon_test_failures == before
                       ? "this backend behaves the way core assumes"
                       : daemoon_test_last_failure);
    message(daemoon_str(DAEMOON_STR_APP_TITLE), body,
            daemoon_test_failures == before ? GFX_OK : GFX_DANGER);
}

/* Unattended, from a flag file, against this application's own save archive and
 * nothing else. See docs/3ds-workflow.md. */
static void run_autotest(void)
{
    daemoon_backend_under_test_t ut;
    daemoon_title_t self;
    daemoon_stream_t *out = NULL;
    char line[256];
    daemoon_strbuf_t sb;
    u64 program_id = 0;
    int failures;

    memset(&self, 0, sizeof(self));
    if (R_FAILED(APT_GetProgramID(&program_id))) {
        return;
    }
    daemoon_3ds_format_title_id(program_id, self.id, sizeof(self.id));
    (void)daemoon_strlcpy(self.name, sizeof(self.name),
                          daemoon_str(DAEMOON_STR_SELFTEST_SELF));
    self.platform = DAEMOON_PLATFORM_3DS;
    self.save_type = DAEMOON_SAVE_SAVEDATA;
    self.size_hint = (unsigned long long)MEDIATYPE_SD;
    self.has_save = 1;

    {
        daemoon_save_t *probe = NULL;

        if (daemoon_3ds_save_backend.open_save(&g_save_ctx, &self, &probe) == DAEMOON_OK) {
            (void)daemoon_3ds_save_backend.close_save(&g_save_ctx, probe);
        } else if (daemoon_3ds_format_own_save(&self, 128) != DAEMOON_OK) {
            message(daemoon_str(DAEMOON_STR_APP_TITLE),
                    daemoon_str(DAEMOON_STR_SELFTEST_NO_ARCHIVE), GFX_WARN);
            return;
        }
    }

    memset(&ut, 0, sizeof(ut));
    ut.name = "3ds";
    ut.backend = &daemoon_3ds_save_backend;
    ut.ctx = &g_save_ctx;
    ut.title = &self;
    ut.other = NULL;
    ut.scratch = g_scratch;
    ut.scratch_len = sizeof(g_scratch);

    failures = daemoon_test_failures;
    daemoon_backend_conformance(&ut);
    failures = daemoon_test_failures - failures;

    /* The suite clears the archive it is pointed at, and that archive is now where
     * the device token lives. Putting it back is not tidiness: without it, running
     * the self test unpairs the console, which is a surprising price for a
     * diagnostic. */
    if (g_config.token[0] != '\0') {
        daemoon_result_t sr = daemoon_3ds_secret_save(&g_env, g_config.token,
                                                      g_config.device_id);

        daemoon_3ds_trace("secret/restored", daemoon_result_code(sr));
    }

    if (g_config.token[0] != '\0') {
        (void)daemoon_3ds_secret_save(&g_env, g_config.token, g_config.device_id);
    }

    /* The screen that has twice gone wrong on hardware, drawn unattended. It
     * asserts nothing - a fault here takes the process down, which is the report. */
    daemoon_3ds_trace("autotest/picker-draw", NULL);
    daemoon_3ds_pick_backup_render_check(&self, 8);
    daemoon_3ds_trace("autotest/picker-drawn", NULL);

    daemoon_strbuf_init(&sb, line, sizeof(line));
    daemoon_strbuf_add(&sb, "build=");
    daemoon_strbuf_add(&sb, DAEMOON_BUILD_STAMP);
    daemoon_strbuf_add(&sb, " target=");
    daemoon_strbuf_add(&sb, self.id);
    daemoon_strbuf_add(&sb, " checks=");
    daemoon_strbuf_add_uint(&sb, (unsigned long long)daemoon_test_checks);
    daemoon_strbuf_add(&sb, " failures=");
    daemoon_strbuf_add_uint(&sb, (unsigned long long)failures);
    if (failures > 0 && daemoon_test_last_failure[0] != '\0') {
        daemoon_strbuf_add(&sb, " first: ");
        daemoon_strbuf_add(&sb, daemoon_test_last_failure);
    }
    daemoon_strbuf_addc(&sb, '\n');

    if (g_env.fs->open(g_env.fs_ctx, DAEMOON_3DS_WORK_DIR "/selftest.txt",
                       DAEMOON_OPEN_WRITE, &out) == DAEMOON_OK) {
        (void)daemoon_stream_write(out, line, sb.len);
        (void)daemoon_stream_close(out);
    }

    message(daemoon_str(DAEMOON_STR_APP_TITLE), line, failures == 0 ? GFX_OK : GFX_DANGER);
}

/* Pairing, unattended, from a payload on the card.
 *
 * The camera is the only part of the QR path a desktop cannot stand in for. This
 * runs everything else as a real ARM binary against a real server: the same parser
 * the camera feeds, the same network backend, the same token write. What is left
 * for hardware is whether a 3DS camera can read a screen, which is a question about
 * optics rather than about this code.
 *
 * The flag file holds exactly what a scan would produce, so the emulator run and
 * the hardware run differ in one step and nothing else.
 */
static void run_autopair(void)
{
    char payload[512];
    daemoon_pair_payload_t parsed;
    daemoon_stream_t *in = NULL;
    daemoon_stream_t *out = NULL;
    daemoon_strbuf_t sb;
    char line[256];
    size_t got = 0;
    daemoon_result_t r;

    if (g_env.fs->open(g_env.fs_ctx, DAEMOON_3DS_AUTOPAIR_PATH, DAEMOON_OPEN_READ,
                       &in) != DAEMOON_OK) {
        return;
    }
    r = daemoon_stream_read(in, payload, sizeof(payload) - 1, &got);
    (void)daemoon_stream_close(in);
    if (r != DAEMOON_OK) {
        got = 0;
    }
    payload[got] = '\0';
    while (got > 0 && (payload[got - 1] == '\n' || payload[got - 1] == '\r')) {
        payload[--got] = '\0';
    }

    daemoon_strbuf_init(&sb, line, sizeof(line));
    daemoon_strbuf_add(&sb, "build=");
    daemoon_strbuf_add(&sb, DAEMOON_BUILD_STAMP);

    r = daemoon_pair_parse(payload, got, &parsed);
    daemoon_strbuf_add(&sb, " parse=");
    daemoon_strbuf_add(&sb, daemoon_result_code(r));

    if (r == DAEMOON_OK) {
        char token[DAEMOON_TOKEN_MAX];
        char device_id[DAEMOON_DEVICE_ID_MAX];

        (void)daemoon_strlcpy(g_config.server_url, sizeof(g_config.server_url),
                              parsed.server);
        g_env.server_url = g_config.server_url;

        r = daemoon_3ds_net_init();
        daemoon_strbuf_add(&sb, " net=");
        daemoon_strbuf_add(&sb, daemoon_result_code(r));

        if (r == DAEMOON_OK) {
            r = daemoon_api_pair(&g_env, "qr", parsed.code, g_config.device_label,
                                 DAEMOON_PLATFORM_3DS, token, sizeof(token),
                                 device_id, sizeof(device_id));
            daemoon_strbuf_add(&sb, " pair=");
            daemoon_strbuf_add(&sb, daemoon_result_code(r));

            if (r == DAEMOON_OK) {
                (void)daemoon_strlcpy(g_config.token, sizeof(g_config.token), token);
                (void)daemoon_strlcpy(g_config.device_id, sizeof(g_config.device_id),
                                      device_id);
                g_env.token = g_config.token;
                r = daemoon_3ds_config_save(DAEMOON_3DS_CONFIG_PATH, &g_config);
                daemoon_strbuf_add(&sb, " save=");
                daemoon_strbuf_add(&sb, daemoon_result_code(r));
                daemoon_strbuf_add(&sb, " device=");
                daemoon_strbuf_add(&sb, device_id);
            }
        }
    }
    daemoon_strbuf_addc(&sb, '\n');

    if (g_env.fs->open(g_env.fs_ctx, DAEMOON_3DS_WORK_DIR "/autopair.txt",
                       DAEMOON_OPEN_WRITE, &out) == DAEMOON_OK) {
        (void)daemoon_stream_write(out, line, sb.len);
        (void)daemoon_stream_close(out);
    }

    message(daemoon_str(DAEMOON_STR_APP_TITLE), line,
            r == DAEMOON_OK ? GFX_OK : GFX_DANGER);
}

/* --------------------------------------------------------------------- main */

int main(void)
{
    daemoon_lang_t lang = DAEMOON_LANG_EN;

    /* The settings come first because the language is one of them, and the
     * language decides which font is loaded. Reading the file needs nothing but
     * stdio, so it can happen before any service is up. */
    (void)daemoon_3ds_config_load(DAEMOON_3DS_CONFIG_PATH, &g_config);

    if (R_FAILED(cfguInit())) {
        g_save_ctx.smdh_language = 1;
    } else {
        lang = select_language();
    }

    if (!daemoon_gfx_init(lang)) {
        return 1;
    }

    /* The font decision, made at runtime rather than at build time.
     *
     * A console's system font is its own region's, so a Korean console draws
     * Hangul and a European one does not - and the selected language is a user
     * choice with nothing to do with the console's region. Rather than bundle a
     * font, ask the font in use whether it has a representative character of the
     * language, and fall back to English when it does not.
     *
     * English is a poor answer for somebody who does not read it. It is a better
     * one than a screen of blank boxes on a confirmation they have to answer, and
     * it is the option docs/fonts.md picked with the sizes written down. */
    /* daemoon_gfx_init already loaded the font for this language, or fell back.
     * When it could not, the UI language follows rather than drawing blanks. */
    if (!daemoon_gfx_language_drawable(lang)) {
        daemoon_3ds_trace("font/fallback", daemoon_lang_code(lang));
        (void)daemoon_gfx_set_language(DAEMOON_LANG_EN);
        daemoon_i18n_set_language(DAEMOON_LANG_EN);
    }
    (void)amInit();

    /* A line the trail can be read from. Without it two runs of the same action
     * are indistinguishable in the file, and "did it get further this time" is the
     * question the file exists to answer. */
    daemoon_3ds_trace("app/start", DAEMOON_BUILD_STAMP);
    {
        /* What survived the last run.
         *
         * Reinstalling a CIA does not touch the SD card, so a token that keeps
         * changing across installs means something is losing it rather than the
         * install replacing it - and the difference is not visible from a device
         * list. The token itself is never written here; a console screen and a
         * trace file both end up in bug reports. */
        char line[96];

        (void)snprintf(line, sizeof(line), "server=%s token=%s device=%s lang=%s",
                       g_config.server_url[0] != '\0' ? "yes" : "no",
                       g_config.token[0] != '\0' ? "yes" : "no",
                       g_config.device_id[0] != '\0' ? g_config.device_id : "-",
                       g_config.language[0] != '\0' ? g_config.language : "auto");
        daemoon_3ds_trace("app/config", line);
    }
    {
        /* Both clocks, because they are not the same one and only one of them
         * decides whether a certificate is valid. mbedtls reads the C library's,
         * so a console where that says 1970 cannot complete a handshake against
         * anything issued this decade no matter what the RTC says. */
        char when[64];

        if (clock_iso8601(NULL, when, sizeof(when)) != DAEMOON_OK) {
            (void)daemoon_strlcpy(when, sizeof(when), "time() unusable");
        }
        daemoon_3ds_trace("app/clock", when);
        (void)snprintf(when, sizeof(when), "osGetTime=%llu",
                       (unsigned long long)osGetTime());
        daemoon_3ds_trace("app/clock-rtc", when);
    }

    g_save_ctx.media = 1; /* MEDIATYPE_SD */
    g_save_ctx.only_with_saves = 1;
    /* Names in whatever script the title carries.
     *
     * This used to be tied to daemoon_gfx_has_language_font(), which answers a
     * narrower question: whether an *extra* region font was loaded. It never is,
     * so every non ASCII name fell back to a product code - and then hardware
     * showed Korean dialog text rendering perfectly. The system font a console
     * ships with is its own region's, and it is the font the HOME menu draws these
     * same names with. There was never a reason to refuse them.
     *
     * The survey still records the real name either way, so a title whose glyphs
     * are genuinely missing is a fact rather than a guess. */
    g_save_ctx.ascii_names = 0;

    daemoon_3ds_ui_init(&g_ui_ctx);
    g_archive.count = 0;

    g_net_ctx.ca_bundle = g_config.ca_bundle;

    g_nds_ctx.rom_dir = DAEMOON_3DS_NDS_ROM_DIR;
    g_nds_ctx.save_dir = DAEMOON_3DS_NDS_SAVE_DIR;

    /* The network is opened once. Doing it per request would mean a soc:U session
     * per sync, and that service does not enjoy being churned. */
    if (daemoon_3ds_config_can_sync(&g_config)) {
        (void)daemoon_3ds_net_init();
    }

    memset(&g_env, 0, sizeof(g_env));
    g_env.save = &daemoon_3ds_save_backend;
    g_env.fs = &daemoon_3ds_fs_backend;
    g_env.ui = &daemoon_3ds_ui_backend;
    g_env.net = &daemoon_3ds_net_backend;
    g_env.net_ctx = &g_net_ctx;
    g_env.save_ctx = &g_save_ctx;
    g_env.fs_ctx = NULL;
    g_env.ui_ctx = &g_ui_ctx;
    g_env.device_label = g_config.device_label;
    g_env.server_url = g_config.server_url;
    g_env.token = g_config.token[0] != '\0' ? g_config.token : NULL;
    g_env.work_dir = DAEMOON_3DS_WORK_DIR;
    g_env.clock_iso8601 = clock_iso8601;
    g_env.scratch = g_scratch;
    g_env.scratch_len = sizeof(g_scratch);

    g_save_ctx.progress = loading_progress;

    /* Names and icons from the last launch, so the loading screen stops paying for
     * a decrypt per title every time. Failing to open it is not an error: without
     * one every lookup goes to the hardware, which is what happened before this
     * existed. */
    (void)g_env.fs->mkdir_p(g_env.fs_ctx, DAEMOON_3DS_WORK_DIR "/cache");
    if (daemoon_3ds_cache_open(DAEMOON_3DS_CACHE_PATH, g_save_ctx.smdh_language,
                               &g_save_ctx.cache) != DAEMOON_OK) {
        g_save_ctx.cache = NULL;
    }

    if (show_library(0) != DAEMOON_OK) {
        message(daemoon_str(DAEMOON_STR_APP_TITLE),
                daemoon_str(DAEMOON_STR_ERR_TITLE_LIST), GFX_DANGER);
    }

    if (g_env.fs->exists(g_env.fs_ctx, DAEMOON_3DS_WORK_DIR "/AUTOTEST")) {
        run_autotest();
        goto done;
    }
    if (g_env.fs->exists(g_env.fs_ctx, DAEMOON_3DS_AUTOPAIR_PATH)) {
        run_autopair();
        goto done;
    }

    while (aptMainLoop()) {
        touchPosition touch;
        int action = -1;
        u32 down;

        hidScanInput();
        down = hidKeysDown();
        hidTouchRead(&touch);

        if (down & KEY_START) {
            break;
        }
        if (down & (KEY_L | KEY_R)) {
            /* The other library, kept from last time: its list, its icons and
             * where the cursor was. Only the first press of each pays for a read. */
            (void)show_library(!g_source_nds);
            continue;
        }
        if (CUR->count > 0) {
            if ((down & KEY_RIGHT) && CUR->selected + 1 < (int)CUR->count) {
                ++CUR->selected;
            }
            if ((down & KEY_LEFT) && CUR->selected > 0) {
                --CUR->selected;
            }
            if ((down & KEY_DOWN) && CUR->selected + GRID_COLS < (int)CUR->count) {
                CUR->selected += GRID_COLS;
            }
            if ((down & KEY_UP) && CUR->selected - GRID_COLS >= 0) {
                CUR->selected -= GRID_COLS;
            }
            if (down & KEY_A) {
                action = 0; /* back up */
            }
            if (down & KEY_Y) {
                action = 1; /* restore */
            }
            if (down & KEY_X) {
                action = 3; /* survey */
            }

            /* Keep the selection on screen. */
            if (CUR->selected / GRID_COLS < CUR->scroll) {
                CUR->scroll = CUR->selected / GRID_COLS;
            }
            if (CUR->selected / GRID_COLS >= CUR->scroll + GRID_ROWS) {
                CUR->scroll = CUR->selected / GRID_COLS - GRID_ROWS + 1;
            }
        }

        daemoon_gfx_frame_begin();
        draw_grid();
        draw_details(down, touch, &action);
        daemoon_gfx_frame_end();

        switch (action) {
        case 0: action_backup(); break;
        case 1: action_restore(); break;
        case 2: action_sync(); break;
        case 3: action_survey(); break;
        case 4: action_self_test(); (void)reload_titles(); break;
        case 5: action_settings(); break;
        default: break;
        }
    }

done:
    daemoon_3ds_trace("app/exit", NULL);
    free_library(&g_lib[LIB_3DS]);
    free_library(&g_lib[LIB_NDS]);
    (void)daemoon_3ds_cache_flush(g_save_ctx.cache, DAEMOON_3DS_CACHE_PATH);
    daemoon_3ds_cache_close(g_save_ctx.cache);
    daemoon_3ds_net_exit();
    amExit();
    cfguExit();
    daemoon_gfx_exit();
    return 0;
}
