static void message(const char *title, const char *body, u32 accent)
{
    /* main.c has its own dialog loop, so it was the one screen the trail could not
     * see - two syncs in a row ended at "uploading" in the file with no sign of the
     * result the user was looking at. */
    daemoon_3ds_trace("ui/message", body);

    while (aptMainLoop()) {
        u32 down;

        hidScanInput();
        down = hidKeysDown();

        daemoon_gfx_frame_begin();
        daemoon_gfx_top();
        daemoon_gfx_rect(0.0f, 0.0f, GFX_TOP_W, 28.0f, accent);
        daemoon_gfx_text(12.0f, 6.0f, 0.6f, GFX_TEXT, title);
        (void)daemoon_gfx_text_wrapped(12.0f, 56.0f, GFX_TOP_W - 24.0f, 0.5f, GFX_TEXT,
                                       body);
        daemoon_gfx_bottom();
        daemoon_gfx_text(12.0f, 100.0f, 0.5f, GFX_TEXT_DIM,
                         daemoon_str(DAEMOON_STR_HINT_CONTINUE));
        daemoon_gfx_frame_end();

        if (down & (KEY_A | KEY_B)) {
            return;
        }
    }
}

/* One place where an operation's outcome becomes a sentence.
 *
 * The wire code goes on the end in brackets. It is an identifier rather than
 * prose - the same kind of thing as a title id - and it is what a photograph in a
 * bug report has to carry, because "동기화 실패" narrows nothing on its own. */
static void report(daemoon_str_id_t op, daemoon_result_t r)
{
    char body[320];
    const char *args[2];

    if (r == DAEMOON_OK) {
        args[0] = daemoon_str(op);
        (void)daemoon_strf(body, sizeof(body), DAEMOON_STR_REPORT_OK, args, 1);
        message(daemoon_str(DAEMOON_STR_APP_TITLE), body, GFX_OK);
        return;
    }

    args[0] = daemoon_str(op);
    args[1] = daemoon_str(daemoon_result_str_id(r));
    (void)daemoon_strf(body, sizeof(body), DAEMOON_STR_REPORT_FAILED, args, 2);
    {
        size_t len = strlen(body);

        (void)snprintf(body + len, sizeof(body) - len, "  [%s]", daemoon_result_code(r));
    }
    message(daemoon_str(DAEMOON_STR_APP_TITLE), body, GFX_DANGER);
}

static void action_backup(void)
{
    char path[DAEMOON_PATH_MAX * 2];
    daemoon_str_ref_t ask;

    if (CUR->count == 0) {
        return;
    }

    /* Backing up writes only to the SD card and cannot lose a save, so this is not
     * one of the confirmations the rules demand. It is here because the button that
     * makes a backup and the button that overwrites a save are next to each other
     * on a console with no pointer, and being told which title is about to be read
     * is worth one press. */
    daemoon_3ds_trace("backup/begin", CUR->titles[CUR->selected].id);
    memset(&ask, 0, sizeof(ask));
    ask.id = DAEMOON_STR_CONFIRM_BACKUP;
    ask.args[0] = CUR->titles[CUR->selected].name;
    ask.nargs = 1;
    if (!g_env.ui->confirm(g_env.ui_ctx, &ask)) {
        return;
    }

    {
        daemoon_result_t r = daemoon_sync_backup_local(&g_env, &g_archive,
                                                       &CUR->titles[CUR->selected], path,
                                                       sizeof(path));

        daemoon_3ds_trace("backup/done", daemoon_result_code(r));
        report(DAEMOON_STR_OP_BACKUP, r);
    }
}

/* The digest of what is on the console right now, so the backup list can say which
 * of its entries would change nothing. Best effort: a title with no archive yet has
 * no digest, and that is not a reason to refuse to show the list. */
static void current_digest(const daemoon_title_t *title, char *out, size_t cap)
{
    daemoon_save_t *save = NULL;
    unsigned long long size = 0;

    out[0] = '\0';
    if (cap < DAEMOON_SHA256_HEX) {
        return;
    }
    if (g_env.save->open_save(g_env.save_ctx, title, &save) != DAEMOON_OK) {
        return;
    }
    if (daemoon_archive_hash_save(&g_env, &g_archive, save, out, &size) != DAEMOON_OK) {
        out[0] = '\0';
    }
    (void)g_env.save->close_save(g_env.save_ctx, save);
}

static void action_restore(void)
{
    char dir[DAEMOON_PATH_MAX * 2];
    char pick[DAEMOON_PATH_MAX * 2];
    char digest[DAEMOON_SHA256_HEX];
    daemoon_strbuf_t sb;
    daemoon_result_t pr;

    if (CUR->count == 0) {
        return;
    }

    daemoon_strbuf_init(&sb, dir, sizeof(dir));
    daemoon_strbuf_add(&sb, DAEMOON_3DS_WORK_DIR);
    daemoon_strbuf_add(&sb, "/backups");
    if (daemoon_strbuf_result(&sb) != DAEMOON_OK) {
        return;
    }

    daemoon_3ds_trace("restore/begin", CUR->titles[CUR->selected].id);
    draw_loading(DAEMOON_STR_LOADING_BACKUPS, 0, 0);
    current_digest(&CUR->titles[CUR->selected], digest, sizeof(digest));
    daemoon_3ds_trace("restore/digest", digest[0] != '\0' ? digest : "-");

    pr = daemoon_3ds_pick_backup(&g_env, dir, &CUR->titles[CUR->selected], digest, pick,
                                 sizeof(pick));
    daemoon_3ds_trace("restore/picked", daemoon_result_code(pr));
    if (pr == DAEMOON_ERR_NOT_FOUND) {
        char none[256];
        const char *args[1];

        args[0] = CUR->titles[CUR->selected].name;
        (void)daemoon_strf(none, sizeof(none), DAEMOON_STR_BACKUP_NONE, args, 1);
        message(daemoon_str(DAEMOON_STR_APP_TITLE), none, GFX_PANEL);
        return;
    }
    if (pr != DAEMOON_OK) {
        return;
    }

    /* The secure value is read before anything is written and put back after. A
     * title that binds its save to this console will otherwise treat the restored
     * save as corrupt and delete it. */
    {
        daemoon_3ds_secure_value_t secure;
        daemoon_result_t sr = daemoon_3ds_read_secure_value(&CUR->titles[CUR->selected], &secure);
        daemoon_result_t r;

        daemoon_3ds_trace("restore/secure-read", daemoon_result_code(sr));
        daemoon_3ds_trace("restore/core", pick);
        r = daemoon_sync_restore_package(&g_env, &g_archive, &CUR->titles[CUR->selected], pick);
        daemoon_3ds_trace("restore/core-done", daemoon_result_code(r));
        report(DAEMOON_STR_OP_RESTORE, r);

        if (r == DAEMOON_OK && sr == DAEMOON_OK && secure.exists) {
            report(DAEMOON_STR_OP_SECURE_VALUE,
                   daemoon_3ds_write_secure_value(&CUR->titles[CUR->selected], &secure));
            daemoon_3ds_trace("restore/secure-written", NULL);
        }
    }
}

static void append_hex32(daemoon_strbuf_t *sb, unsigned long value)
{
    static const char digits[] = "0123456789ABCDEF";
    char hex[11];
    int k;

    hex[0] = '0';
    hex[1] = 'x';
    for (k = 0; k < 8; ++k) {
        hex[2 + k] = digits[(value >> ((7 - k) * 4)) & 0xf];
    }
    hex[10] = '\0';
    daemoon_strbuf_add(sb, hex);
}

/* Phase 2: the whole sync path, which has been running on a desktop since Phase
 * 0. Nothing about it is new here except the network underneath it. */
static void action_sync(void)
{
    daemoon_sync_stats_t stats;
    char body[256];
    daemoon_result_t r;

    if (CUR->count == 0) {
        return;
    }
    if (!daemoon_3ds_config_can_sync(&g_config)) {
        message(daemoon_str(DAEMOON_STR_APP_TITLE),
                daemoon_str(DAEMOON_STR_ERR_NO_SERVER), GFX_WARN);
        return;
    }

    memset(&stats, 0, sizeof(stats));
    daemoon_3ds_trace("sync/begin", CUR->titles[CUR->selected].id);
    r = daemoon_sync_title(&g_env, &g_archive, &CUR->titles[CUR->selected], &stats);
    daemoon_3ds_trace("sync/done", daemoon_result_code(r));

    if (r != DAEMOON_OK) {
        report(DAEMOON_STR_OP_SYNC, r);
        return;
    }
    {
        char counts[4][12];
        const char *args[4];
        size_t i;
        const unsigned n[4] = { stats.uploaded, stats.downloaded, stats.skipped,
                                stats.conflicts };

        for (i = 0; i < 4; ++i) {
            (void)snprintf(counts[i], sizeof(counts[i]), "%u", n[i]);
            args[i] = counts[i];
        }
        (void)daemoon_strf(body, sizeof(body), DAEMOON_STR_SYNC_RESULT, args, 4);
    }
    message(daemoon_str(DAEMOON_STR_APP_TITLE), body, GFX_OK);
}

