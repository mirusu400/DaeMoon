/* 3DS entry point. Phase 1: local backup and restore, no server involved.
 *
 * Everything below the platform layer already exists and is tested on a desktop.
 * This file assembles a daemoon_env_t out of libctru and draws a grid of game
 * icons, because the question this application asks - which game's save do you
 * want to overwrite - is not one anybody should answer from a product code.
 *
 * The scratch buffer is static rather than malloc'd. The 3DS heap fragments
 * badly, this one lives for the whole run, and there is nothing to gain from
 * putting it on the heap and a slow loss of headroom to lose.
 */
#include "daemoon_3ds.h"
#include "gfx.h"
#include "icons.h"

#include "../../../tools/test/backend_conformance.h"
#include "../../../tools/test/test.h"

