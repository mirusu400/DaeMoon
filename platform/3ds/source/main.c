/* Enough icons for a console with a lot of saves. Past this the grid still works
 * and the rest draw a placeholder, which is a better failure than refusing to
 * list them. */
#define MAX_ICONS 128

#define GRID_COLS   6
#define GRID_ROWS   3
#define GRID_CELL_W 64.0f
#define GRID_CELL_H 74.0f
#define GRID_X      ((GFX_TOP_W - GRID_COLS * GRID_CELL_W) / 2.0f)
#define GRID_Y      36.0f
#define GRID_PAGE   (GRID_COLS * GRID_ROWS)

/* libctru's weak default is 32 KiB, and `StackSize` in app.rsf does not override
 * it - the exheader value is not what the main thread ends up running on. Thirty
 * two kilobytes is not enough for this application:
 *
 *   - the first restore ever run on hardware died because one function wanted
 *     fifty of them for a single frame. That frame is gone, but the ceiling it hit
 *     was this one, and it sat about thirty kilobytes above the floor.
 *   - curl and mbedtls are linked in. A TLS handshake alone is tens of kilobytes
 *     of stack, and Phase 2 is where https starts mattering.
 *
 * A quarter of a megabyte of address space costs nothing on a console with tens of
 * megabytes of it, and the failure it prevents is a data abort with no message. */
unsigned int __stacksize__ = 256 * 1024;

static unsigned char g_scratch[64 * 1024];
static daemoon_archive_ctx_t g_archive;

static daemoon_3ds_save_ctx_t g_save_ctx;
static daemoon_3ds_nds_ctx_t  g_nds_ctx;
static daemoon_3ds_net_ctx_t  g_net_ctx;
static daemoon_3ds_config_t   g_config;
/* Which library is on screen: the console's own titles, or the DS saves
 * nds-bootstrap keeps as plain files. Phase 2 syncs the second one first because
 * nothing about it can fail in a way unique to the platform. */
static int g_source_nds;
static daemoon_3ds_ui_ctx_t   g_ui_ctx;
static daemoon_env_t          g_env;

/* Both libraries, kept side by side.
 *
 * Switching used to free one list and enumerate the other from scratch, and on a
 * console with a real library that is a decrypt per title and several seconds -
 * every single press of L or R. The lists do not change while the application is
 * running unless it changes them, so they are read once and kept, along with where
 * the cursor was in each: coming back to a library and finding it where you left
 * it is most of what makes two libraries feel like one application. */
typedef struct {
    daemoon_title_t   *titles;
    size_t             count;
    daemoon_3ds_icon_t icons[MAX_ICONS];
    int                loaded;
    int                selected;
    int                scroll;
} library_t;

#define LIB_3DS 0
#define LIB_NDS 1

static library_t g_lib[2];

/* Shorthand for whichever library is on screen. */
#define CUR (&g_lib[g_source_nds ? LIB_NDS : LIB_3DS])

/* --------------------------------------------------------------------- i18n */

/* Which language the console itself is set to. Also the SMDH slot a title's name
 * is read from, which is why the two are worked out together. */
static daemoon_lang_t console_language(void)
{
    u8 code = 0;
    daemoon_lang_t lang = DAEMOON_LANG_EN;

    g_save_ctx.smdh_language = 1; /* English, until the console says otherwise */

    if (R_FAILED(CFGU_GetSystemLanguage(&code))) {
        return lang;
    }
    switch (code) {
    case CFG_LANGUAGE_JP: (void)daemoon_i18n_language_from_code("ja", &lang); break;
    case CFG_LANGUAGE_FR: (void)daemoon_i18n_language_from_code("fr", &lang); break;
    case CFG_LANGUAGE_DE: (void)daemoon_i18n_language_from_code("de", &lang); break;
    case CFG_LANGUAGE_ES: (void)daemoon_i18n_language_from_code("es", &lang); break;
    case CFG_LANGUAGE_ZH: (void)daemoon_i18n_language_from_code("zh-Hans", &lang); break;
    case CFG_LANGUAGE_KO: (void)daemoon_i18n_language_from_code("ko", &lang); break;
    case CFG_LANGUAGE_TW: (void)daemoon_i18n_language_from_code("zh-Hant", &lang); break;
    default:              lang = DAEMOON_LANG_EN; break;
    }

    /* The SMDH title index is the console's own language numbering, so a title's
     * name comes back in the language the HOME menu shows it in. This follows the
     * console even when the UI language does not: a game's name is the game's, not
     * a translation. */
    g_save_ctx.smdh_language = (int)code;
    return lang;
}

/* The UI language: the user's choice when they made one, the console's otherwise.
 *
 * Kept apart from the console's setting on purpose. Empty in the file is not the
 * same as "en" - a console later switched to Japanese should follow, and somebody
 * who picked English on a Japanese console should not be overruled by it. */
static daemoon_lang_t select_language(void)
{
    daemoon_lang_t lang = console_language();
    daemoon_lang_t chosen;

    if (g_config.language[0] != '\0' &&
        daemoon_i18n_language_from_code(g_config.language, &chosen) == DAEMOON_OK) {
        lang = chosen;
    }
    daemoon_i18n_set_language(lang);
    return lang;
}

/* -------------------------------------------------------------------- clock */

/* The console's clock, for manifest created_at.
 *
 * Never used to decide anything - the RTC is user settable and the rules say so
 * twice - but it is what a person recognises their own backups by, and without
 * this hook every backup in the picker was dated 1970-01-01, which is worse than
 * useless because it looks like a bug in the packaging.
 *
 * It is also a check on something else. mbedtls validates a certificate's dates
 * against the same C library clock, so a console reading 1970 cannot complete a
 * TLS handshake against any certificate issued this decade. If the dates in the
 * backup list are real, that half of https is going to work. */
static daemoon_result_t clock_iso8601(void *ctx, char *buf, size_t cap)
{
    time_t now = time(NULL);
    struct tm utc;

    (void)ctx;
    if (now <= 0 || gmtime_r(&now, &utc) == NULL) {
        return DAEMOON_ERR_UNSUPPORTED;
    }
    if (strftime(buf, cap, "%Y-%m-%dT%H:%M:%SZ", &utc) == 0) {
        return DAEMOON_ERR_BUFFER_TOO_SMALL;
    }
    return DAEMOON_OK;
}

/* ------------------------------------------------------------------- titles */

static unsigned long long tid_of(const daemoon_title_t *t)
{
    unsigned long long id = 0;

    (void)daemoon_3ds_parse_title_id(t->id, &id);
    return id;
}

static void free_library(library_t *lib)
{
    size_t i;

    for (i = 0; i < MAX_ICONS; ++i) {
        daemoon_3ds_icon_free(&lib->icons[i]);
    }
    if (lib->titles != NULL) {
        /* Freed by the backend that produced it, which is why the pairing below
         * is set before anything is released. */
        g_env.save = (lib == &g_lib[LIB_NDS]) ? &daemoon_3ds_nds_backend
                                              : &daemoon_3ds_save_backend;
        g_env.save_ctx = (lib == &g_lib[LIB_NDS]) ? (void *)&g_nds_ctx
                                                  : (void *)&g_save_ctx;
        g_env.save->free_titles(g_env.save_ctx, lib->titles, lib->count);
        lib->titles = NULL;
        lib->count = 0;
    }
    lib->loaded = 0;
}

/* One frame of the loading screen. Reading the list opens every save archive on
 * the console, so this runs for as long as that takes and a still screen would
 * look like a hang. */
static void draw_loading(daemoon_str_id_t what, unsigned done, unsigned total)
{
    char line[160];

    daemoon_gfx_frame_begin();
    daemoon_gfx_top();
    daemoon_gfx_rect(0.0f, 0.0f, GFX_TOP_W, 28.0f, GFX_ACCENT_D);
    daemoon_gfx_text(12.0f, 6.0f, 0.55f, GFX_TEXT, daemoon_str(DAEMOON_STR_APP_TITLE));

    if (total > 0) {
        (void)snprintf(line, sizeof(line), "%s  %u/%u", daemoon_str(what), done, total);
    } else {
        (void)daemoon_strlcpy(line, sizeof(line), daemoon_str(what));
    }
    daemoon_gfx_text(12.0f, 100.0f, 0.5f, GFX_TEXT_DIM, line);

    if (total > 0) {
        float w = (GFX_TOP_W - 24.0f) * (float)done / (float)total;

        daemoon_gfx_rect(12.0f, 126.0f, GFX_TOP_W - 24.0f, 6.0f, GFX_PANEL);
        daemoon_gfx_rect(12.0f, 126.0f, w, 6.0f, GFX_ACCENT);
    }
    daemoon_gfx_frame_end();
}

static void loading_progress(void *user, unsigned done, unsigned total)
{
    (void)user;
    draw_loading(DAEMOON_STR_LOADING_TITLES, done, total);
}

/* Points the environment at one library's backend. The backend and its context
 * change together: getting that pair out of step would point save operations at
 * the wrong library entirely. */
static void select_backend(int nds)
{
    if (nds) {
        g_env.save = &daemoon_3ds_nds_backend;
        g_env.save_ctx = &g_nds_ctx;
    } else {
        g_env.save = &daemoon_3ds_save_backend;
        g_env.save_ctx = &g_save_ctx;
    }
}

static daemoon_result_t load_library(int nds)
{
    library_t *lib = &g_lib[nds ? LIB_NDS : LIB_3DS];
    daemoon_result_t r;
    size_t i;

    free_library(lib);
    select_backend(nds);

    r = g_env.save->list_titles(g_env.save_ctx, &lib->titles, &lib->count);
    if (r != DAEMOON_OK) {
        return r;
    }

    for (i = 0; i < lib->count && i < MAX_ICONS; ++i) {
        draw_loading(DAEMOON_STR_LOADING_ICONS, (unsigned)i, (unsigned)lib->count);
        if (nds) {
            /* Out of the ROM's banner, beside the save. A .sav next to a file
             * called "5684(Dsi0143) 포켓몬화이트 (K)" is exactly where a name
             * stops helping and a picture starts. */
            static unsigned char pixels[DAEMOON_3DS_ICON_BYTES];

            if (daemoon_3ds_nds_icon_read(g_nds_ctx.rom_dir, lib->titles[i].name,
                                          pixels) == DAEMOON_OK) {
                (void)daemoon_3ds_icon_upload(pixels, &lib->icons[i]);
            }
        } else {
            /* The same SMDH the name came from, already in the cache by now, so
             * this loop costs a texture upload rather than a decrypt per title. */
            (void)daemoon_3ds_icon_upload(
                daemoon_3ds_cache_icon(g_save_ctx.cache, g_save_ctx.media,
                                       tid_of(&lib->titles[i])),
                &lib->icons[i]);
        }
    }
    if (!nds) {
        /* Written back once the list is complete, not per title: a title that was
         * skipped this run is a title that is no longer installed, and that is
         * only known at the end. */
        (void)daemoon_3ds_cache_flush(g_save_ctx.cache, DAEMOON_3DS_CACHE_PATH);
    }
    if (lib->selected >= (int)lib->count) {
        lib->selected = lib->count > 0 ? (int)lib->count - 1 : 0;
    }
    lib->loaded = 1;
    return DAEMOON_OK;
}

/* Makes the library on screen the current one, reading it only if it has never
 * been read. This is what L and R call, and it is why they are now instant. */
static daemoon_result_t show_library(int nds)
{
    g_source_nds = nds;
    select_backend(nds);
    if (g_lib[nds ? LIB_NDS : LIB_3DS].loaded) {
        return DAEMOON_OK;
    }
    return load_library(nds);
}

/* Re-reads the library on screen. For after something changed it. */
static daemoon_result_t reload_titles(void)
{
    return load_library(g_source_nds);
}

